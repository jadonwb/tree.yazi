-- Decode one code point at byte index `i`. Returns `cp, advance, true` on a
-- valid sequence, or `nil, advance, false` where `advance` is the number of
-- bytes to skip before the next decode attempt (one replacement char per
-- invalid chunk, matching Rust's `utf8_chunks`).
local function decode(s, i)
	local b1 = s:byte(i)
	if b1 < 0x80 then
		return b1, 1, true
	end
	local b2 = s:byte(i + 1)
	if b1 >= 0xC2 and b1 <= 0xDF then
		if not b2 or b2 < 0x80 or b2 > 0xBF then
			return nil, 1, false
		end
		return (b1 - 0xC0) * 0x40 + (b2 - 0x80), 2, true
	elseif b1 < 0xE0 or b1 > 0xF4 then
		return nil, 1, false
	elseif b1 <= 0xEF then
		if not b2 or b2 < 0x80 or b2 > 0xBF then
			return nil, 1, false
		end
		if (b1 == 0xE0 and b2 < 0xA0) or (b1 == 0xED and b2 > 0x9F) then
			return nil, 1, false
		end
		local b3 = s:byte(i + 2)
		if not b3 then
			return nil, 2, false
		end
		if b3 < 0x80 or b3 > 0xBF then
			return nil, 2, false
		end
		return (b1 - 0xE0) * 0x1000 + (b2 - 0x80) * 0x40 + (b3 - 0x80), 3, true
	else
		if not b2 or b2 < 0x80 or b2 > 0xBF then
			return nil, 1, false
		end
		if (b1 == 0xF0 and b2 < 0x90) or (b1 == 0xF4 and b2 > 0x8F) then
			return nil, 1, false
		end
		local b3 = s:byte(i + 2)
		if not b3 then
			return nil, 2, false
		end
		if b3 < 0x80 or b3 > 0xBF then
			return nil, 2, false
		end
		local b4 = s:byte(i + 3)
		if not b4 then
			return nil, 3, false
		end
		if b4 < 0x80 or b4 > 0xBF then
			return nil, 3, false
		end
		return (b1 - 0xF0) * 0x40000 + (b2 - 0x80) * 0x1000 + (b3 - 0x80) * 0x40 + (b4 - 0x80), 4, true
	end
end

local REPLACEMENT = "\239\191\189" -- U+FFFD

-- Fast path: return immediately when every byte is ASCII.
function M.apply(s)
	if not s or s == "" then
		return s
	end
	local n = #s
	local i = 1
	while i <= n and s:byte(i) < 0x7f do
		i = i + 1
	end
	if i > n then
		return s
	end
	local out = { s:sub(1, i - 1) }
	while i <= n do
		local cp, advance, ok = decode(s, i)
		if not ok then
			out[#out + 1] = REPLACEMENT
			i = i + advance
		else
			local rep = T[cp]
			if rep then
				out[#out + 1] = rep
			else
				out[#out + 1] = s:sub(i, i + advance - 1)
			end
			i = i + advance
		end
	end
	return table.concat(out)
end

return M
